        MATL        CHAR(5)       NOT NULL,
        THELOAI     NVARCHAR(50)  NOT NULL,
        CONSTRAINT PK_THELOAI PRIMARY KEY (MATL),
        CONSTRAINT UQ_THELOAI_TEN UNIQUE (THELOAI)
    );
END;
GO


            CONSTRAINT DF_DOCGIA_HOATDONG DEFAULT (1),
        CONSTRAINT PK_DOCGIA PRIMARY KEY (MADG),
        CONSTRAINT UQ_DOCGIA_SOCMND UNIQUE (SOCMND),
